#!/usr/bin/env python3
"""
14_revision_analyses.py: numbers added to the manuscript in response to the
pre-submission review (26 Oct 2026), recomputed from the result files.

  1. ECE and Brier score of the primary model, with patient-level bootstrap CIs
     (2000 resamples, seed 42, as in burnml.bootstrap_ci).
  2. Per-class AUC bootstrap CIs (from the run-of-record metrics).
  3. Full-thickness sensitivity per patient (patients numbered 1..N as in the paper).
  4. Interior learning-rate selections of the widest random-init grid, per task.
  5. Learning curves stratified by whether the patient with most full-thickness
     crops was among the training patients (folds holding that patient out excluded).
  6. Grad-CAM randomisation check, including flat-map counts when the gradcam.json
     was written by 10_gradcam.py 2.0.2 or later.

Usage:
    python scripts/14_revision_analyses.py --run1 run1/results --results results \
        --out RESULTS_LEDGER_ADDENDUM.md
"""
import argparse, collections, csv, glob, json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import burnml


def oof(R1, task):
    rows = list(csv.DictReader(open(f"{R1}/{task}/efficientnetb0/oof_predictions.csv")))
    L = burnml.TASKS[task][0]
    y = np.array([L.index(r["true_label"]) for r in rows])
    P = np.array([[float(r["p_" + c]) for c in L] for r in rows])
    return L, y, P, np.array([r["patient_group"] for r in rows])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run1", required=True); ap.add_argument("--results", required=True)
    ap.add_argument("--out", default="RESULTS_LEDGER_ADDENDUM.md")
    a = ap.parse_args(); R1, R2 = a.run1, a.results
    man = list(csv.DictReader(open(f"{R1}/manifest.csv")))
    groups = sorted({r["patient_group"] for r in man}); pid = {g: i + 1 for i, g in enumerate(groups)}
    dom = collections.Counter(r["patient_group"] for r in man if r["class"] == "Full_thickness_burn").most_common(1)[0][0]
    out = ["# Results ledger addendum (pre-submission review, 26 Oct 2026)", "",
           f"Generated by `scripts/14_revision_analyses.py` from `{R1}` (run of record) and `{R2}`.", ""]
    out += ["## 1. Calibration with patient-level bootstrap CIs", "", "| Task | ECE (95% CI) | Brier (95% CI) |", "|---|---|---|"]
    for task in ("classification", "detection"):
        L, y, P, g = oof(R1, task); c = burnml.calibration_metrics(P, y, L)
        rng = np.random.RandomState(42); uniq = np.array(sorted(set(g))); ix = {u: np.where(g == u)[0] for u in uniq}; e, b = [], []
        for _ in range(2000):
            idx = np.concatenate([ix[u] for u in rng.choice(uniq, size=len(uniq), replace=True)])
            cc = burnml.calibration_metrics(P[idx], y[idx], L); e.append(cc["ece"]); b.append(cc["brier"])
        el, eh = np.percentile(e, [2.5, 97.5]); bl, bh = np.percentile(b, [2.5, 97.5])
        out.append(f"| {task} | {c['ece']:.3f} ({el:.3f}–{eh:.3f}) | {c['brier']:.3f} ({bl:.3f}–{bh:.3f}) |")
    out += ["", "## 2. Per-class AUC with bootstrap CIs (run-of-record metrics.json)", ""]
    for task in ("classification", "detection"):
        m = json.load(open(f"{R1}/{task}/efficientnetb0/metrics.json"))
        out.append(f"- {task}: " + "; ".join(f"{k.split('.')[0].replace('_', ' ')} {m['per_class'][k.split('.')[0]]['auc']:.3f} ({v[0]:.3f}–{v[1]:.3f})"
                                             for k, v in m["ci95"].items() if k.endswith(".auc")))
    L, y, P, g = oof(R1, "classification"); k = L.index("Full_thickness_burn"); pred = P.argmax(1)
    per = sorted(((pid[p], int(((g == p) & (y == k) & (pred == k)).sum()), int(((g == p) & (y == k)).sum())) for p in set(g[y == k])), key=lambda r: r[0])
    sens = [h / n for _, h, n in per]
    out += ["", "## 3. Full-thickness sensitivity per patient", "",
            ", ".join(f"patient {p}: {h}/{n}" for p, h, n in per),
            f"Patient-weighted mean {np.mean(sens):.3f}; patients at or below 0.33: {sum(s <= 0.334 for s in sens)} of {len(sens)}; at zero: {sum(s == 0 for s in sens)}.", ""]
    out += ["## 4. Widest random-init grid: selected learning rate inside the grid", ""]
    for task in ("classification", "detection"):
        fs = sorted(glob.glob(f"{R1}/{task}/efficientnetb0_randominit_bracket/folds/fold_*.json"))
        if not fs:
            out.append(f"- {task}: fold records not found"); continue
        inside = 0
        for f in fs:
            d = json.load(open(f)); grid = sorted(float(x) for x in d["lr_selection_inner_ce"]); ch = float(d["chosen_lr"])
            inside += grid[0] < ch < grid[-1]
        out.append(f"- {task}: {inside} of {len(fs)} folds")
    out += ["", f"## 5. Learning curves stratified by patient {pid[dom]} in training (folds holding it out excluded)", "",
            "| Task | Patient in training | 6 | 9 | 12 |", "|---|---|---|---|---|"]
    for task in ("classification", "detection"):
        L = burnml.TASKS[task][0]; cells = {True: [], False: []}
        for n in (6, 9, 12):
            st = {True: [[], []], False: [[], []]}; cnt = collections.Counter()
            for f in glob.glob(f"{R2}/{task}/learning_curve/efficientnetb0/n{n}_s*/folds/fold_*.json"):
                d = json.load(open(f))
                if dom in d["held_out_patients"]:
                    continue
                s = dom in d["training_patients"]; cnt[s] += 1
                st[s][0] += [L.index(t) if isinstance(t, str) else int(t) for t in d["true_labels"]]; st[s][1] += d["probs"]
            for s in (True, False):
                yy, pp = np.array(st[s][0]), np.array(st[s][1])
                cells[s].append(f"{burnml.compute_metrics(yy, pp.argmax(1), pp, L)['macro_auc']:.3f} ({cnt[s]})" if len(yy) else "—")
        out += [f"| {task} | yes | " + " | ".join(cells[True]) + " |", f"| {task} | no | " + " | ".join(cells[False]) + " |"]
    out += ["", "## 6. Grad-CAM randomisation check (first repeated split, pretrained)", ""]
    for task in ("classification", "detection"):
        fp = f"{R2}/{task}/repeats/r1/efficientnetb0/report/gradcam.json"
        if not os.path.exists(fp):
            out.append(f"- {task}: gradcam.json not found"); continue
        sc = json.load(open(fp))["sanity_check"]
        out.append(f"- {task}: " + "; ".join(
            f"{st}: Spearman {v['spearman']:+.3f}, SSIM {v['ssim']:.3f}" +
            (f", flat {v['undefined_flat_maps']}/{v['comparisons']}, excl. flat {v['spearman_defined_only']:+.3f}" if "undefined_flat_maps" in v else ", flat-map counts not in this file (rerun 10_gradcam.py 2.0.2)")
            for st, v in sc.items()))
    open(a.out, "w").write("\n".join(out) + "\n"); print(f"Wrote {a.out}")


if __name__ == "__main__":
    main()
